package main

import (
	"bytes"
	"crypto"

	"github.com/cloudflare/circl/group"
	"github.com/si-co/vpir-code/lib/client"
	"github.com/si-co/vpir-code/lib/database"
	"github.com/si-co/vpir-code/lib/server"
)

// ddhCell is S4, primitive cmp-vpir-dh in simulations/simul.go: one bit per
// byte in a square matrix, with per-row digests on P-256.
type ddhCell struct {
	g          geometry
	seed       uint64
	rows, cols int
	data       []byte // the seeded database, bit i is data[i]&1
	db         *database.Elliptic
	srv, stale *server.DH
	cli, other *client.DH
}

func newDDHCell(g geometry, seed uint64) (cell, error) {
	rows, cols := database.CalculateNumRowsAndColumns(g.dbBits, true)
	return &ddhCell{g: g, seed: seed, rows: rows, cols: cols, data: streamBytes(seed, "db", rows*cols)}, nil
}

func (c *ddhCell) params() map[string]any {
	return map[string]any{
		"scheme": "DDH (client.NewDH)", "curve": "P-256", "hash": crypto.BLAKE2b_256.String(),
		"element_bytes": c.db.ElementSize, "db_rows": c.rows, "db_cols": c.cols,
	}
}

// analytical is null: simulations/simul.go (pirElliptic) counts len() of the
// same byte messages and gives no formula.
func (c *ddhCell) analytical() Analytical { return Analytical{} }

// setup times the whole constructor because it computes the row digests
// inline (computeDigests is unexported). Its only non-digest work is copying
// the pre-generated bytes from the reader and masking them to bits.
func (c *ddhCell) setup() offlineCost {
	pre := timed(func() {
		c.db = database.CreateRandomEllipticWithDigest(bytes.NewReader(c.data), c.g.dbBits, group.P256, true)
	})
	c.srv = server.NewDH(c.db)
	// NewDH checks the row digests against the global digest, the client's
	// offline verification.
	cl := timed(func() { c.cli = client.NewDH(stream(c.seed, "client"), &c.db.Info) })
	c.other = client.NewDH(stream(c.seed, "shadow-client"), &c.db.Info)
	n := len(c.db.SubDigests) + len(c.db.Digest)
	return offlineCost{serverPreproc: pre, clientOffline: cl, downBytes: n, downHintBytes: n, storageBytes: n}
}

func (c *ddhCell) query(index int) ([][]byte, span) {
	var q []byte
	var err error
	sp := timed(func() { q, err = c.cli.QueryBytes(index) })
	must(err)
	return [][]byte{q}, sp
}

func (c *ddhCell) answer(_ int, q []byte) ([]byte, span) {
	var a []byte
	var err error
	sp := timed(func() { a, err = c.srv.AnswerBytes(q) })
	must(err)
	return a, sp
}

func (c *ddhCell) reconstruct(answers [][]byte, sp *span) ([]byte, error) {
	var res interface{}
	var err error
	timeInto(sp, func() { res, err = c.cli.ReconstructBytes(answers[0]) })
	if err != nil {
		return nil, err
	}
	return []byte{res.(byte)}, nil
}

func (c *ddhCell) shadowAnswer(index, _ int) []byte {
	q, err := c.other.QueryBytes(index)
	must(err)
	a, err := c.srv.AnswerBytes(q)
	must(err)
	return a
}

// flipBits is the whole answer: the client checks every row's element
// against its digest.
func (c *ddhCell) flipBits(int) []bitRange {
	return []bitRange{bytesRange(0, c.rows*c.db.ElementSize)}
}

func (c *ddhCell) truth(index int) []byte { return []byte{c.data[index] & 1} }

func (c *ddhCell) buildStale() {
	flipped := make([]byte, len(c.data))
	for i, b := range c.data {
		flipped[i] = b ^ 1
	}
	c.stale = server.NewDH(database.CreateRandomEllipticWithDigest(bytes.NewReader(flipped), c.g.dbBits, group.P256, true))
}

func (c *ddhCell) staleAnswer(_ int, q []byte) []byte {
	a, err := c.stale.AnswerBytes(q)
	must(err)
	return a
}
