// xorCell is M0 (classic two-server PIR) and M1 (the same scheme over a
// database whose blocks carry Merkle proofs). At the pin, client.Query sends
// XOR secret shares of a one-hot column vector to each server; the server is
// unaware of Merkle and the client verifies inside Reconstruct.
type xorCell struct {
	g          geometry
	seed       uint64
	merkle     bool
	data       []byte // the seeded database, record i at data[i*rb:(i+1)*rb]
	db         *database.Bytes
	srv, stale [2]*server.PIR
	cli, other *client.PIR
	row        int // the row the main client last queried, as its upstream state holds it
}

func newXORCell(g geometry, seed uint64, merkle bool) *xorCell {
	c := &xorCell{g: g, seed: seed, merkle: merkle, data: streamBytes(seed, "db", g.dbBits/8)}
	if !merkle {
		// Classic PIR has no preprocessing, so the database is laid out once here.
		c.db = database.CreateRandomBytes(bytes.NewReader(c.data), c.g.dbBits, c.g.rows, c.g.recordBytes)
	}
	return c
}

func (c *xorCell) params() map[string]any {
	p := map[string]any{
		"scheme": "two-server XOR PIR (client.NewPIR, server.NewPIR)", "servers": 2, "query": "xor_shares",
		"db_rows": c.db.NumRows, "db_cols": c.db.NumColumns, "record_bytes": c.g.recordBytes,
		"stored_block_bytes": c.db.BlockSize,
	}
	if c.merkle {
		p["scheme"] = "two-server Merkle APIR (database.CreateRandomMerkle)"
		p["hash"] = "BLAKE3"
		p["proof_bytes"] = c.db.ProofLen
	}
	return p
}

// analytical is null: upstream gives no size formula for these messages
// (simulations/multi counts len() of the bytes sent).
func (c *xorCell) analytical() Analytical { return Analytical{} }

// setup for M1 times the whole constructor: it builds the Merkle tree and
// writes each block followed by its proof. Its only non-preprocessing work is
// copying the pre-generated bytes from the reader.
func (c *xorCell) setup() offlineCost {
	var cost offlineCost
	if c.merkle {
		cost.serverPreproc = timed(func() {
			c.db = database.CreateRandomMerkle(bytes.NewReader(c.data), c.g.dbBits, c.g.rows, c.g.recordBytes)
		})
		// The client keeps only the Merkle root.
		cost.downBytes, cost.downHintBytes, cost.storageBytes = len(c.db.Root), len(c.db.Root), len(c.db.Root)
	}
	for k := range c.srv {
		c.srv[k] = server.NewPIR(c.db, 1)
	}
	cost.clientOffline = timed(func() { c.cli = client.NewPIR(stream(c.seed, "client"), &c.db.Info) })
	c.other = client.NewPIR(stream(c.seed, "shadow-client"), &c.db.Info)
	return cost
}

func (c *xorCell) query(index int) ([][]byte, span) {
	var qs [][]byte
	sp := timed(func() { qs = c.cli.Query(index, len(c.srv)) })
	c.row, _ = utils.VectorToMatrixIndices(index, c.db.NumColumns)
	return qs, sp
}

// refuseDecode stops M1 answers that upstream cannot decode without
// allocating far more memory than this machine has. reconstructPIR XORs the
// queried row's blocks, unpads the sum and passes its last ProofLen bytes to
// merkle.DecodeProof, which makes a slice of as many hashes as the proof's
// first four bytes say before reading any of them. A corrupted sum makes that
// count random, up to 2^32 slice headers (96 GiB). When the count is larger
// than a block can hold, the read that follows always panics, so the answer is
// rejected either way and the adapter skips the call.
func (c *xorCell) refuseDecode(answers [][]byte) string {
	if !c.merkle {
		return ""
	}
	bs := c.db.BlockSize
	sum := make([]byte, bs)
	for _, a := range answers {
		if len(a) < (c.row+1)*bs {
			return ""
		}
		for i, b := range a[c.row*bs : (c.row+1)*bs] {
			sum[i] ^= b
		}
	}
	// UnPadBlock: trailing zeros, then the 0x80 pad byte.
	trimmed := bytes.TrimRight(sum, "\x00")
	if len(trimmed) <= c.db.ProofLen {
		return "" // upstream's own slicing fails first, with no large allocation
	}
	block := trimmed[:len(trimmed)-1]
	n := binary.LittleEndian.Uint32(block[len(block)-c.db.ProofLen:])
	if 4+32*uint64(n) <= uint64(bs) {
		return ""
	}
	return fmt.Sprintf("the decoded Merkle proof claims %d hashes, more than a %d-byte block holds, so merkle.DecodeProof would allocate %.1f GiB of slice headers and then panic",
		n, bs, float64(n)*24/(1<<30))
}

func (c *xorCell) answer(k int, q []byte) ([]byte, span) {
	var a []byte
	sp := timed(func() { a = c.srv[k].Answer(q) })
	return a, sp
}

func (c *xorCell) reconstruct(answers [][]byte, sp *span) ([]byte, error) {
	var out []byte
	var err error
	timeInto(sp, func() { out, err = c.cli.Reconstruct(answers) })
	return out, err
}

func (c *xorCell) shadowAnswer(index, k int) []byte {
	return c.srv[k].Answer(c.other.Query(index, len(c.srv))[k])
}

// flipBits is the stored block in the queried row, which the client XORs.
// For M1 the block is the record, its encoded proof and a 0x80 pad byte.
// UnPadBlock only trims zero bytes, so of the pad byte only its top bit
// changes the output.
func (c *xorCell) flipBits(index int) []bitRange {
	bs := c.db.BlockSize
	off := (index / c.db.NumColumns) * bs
	if !c.merkle {
		return []bitRange{bytesRange(off, bs)}
	}
	pad := off + bs - 1
	return []bitRange{bytesRange(off, bs-1), {first: 8*pad + 7, n: 1}}
}

func (c *xorCell) truth(index int) []byte {
	rb := c.g.recordBytes
	return c.data[index*rb : (index+1)*rb]
}

func (c *xorCell) buildStale() {
	flipped := make([]byte, len(c.data))
	for i, b := range c.data {
		flipped[i] = ^b
	}
	var db *database.Bytes
	if c.merkle {
		db = database.CreateRandomMerkle(bytes.NewReader(flipped), c.g.dbBits, c.g.rows, c.g.recordBytes)
	} else {
		db = database.CreateRandomBytes(bytes.NewReader(flipped), c.g.dbBits, c.g.rows, c.g.recordBytes)
	}
	for k := range c.stale {
		c.stale[k] = server.NewPIR(db, 1)
	}
}

func (c *xorCell) staleAnswer(k int, q []byte) []byte { return c.stale[k].Answer(q) }
